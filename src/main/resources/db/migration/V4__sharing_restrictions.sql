-- ---------------------------------------------------------------------------
-- TrustVault Flyway Migration V4: Sharing Restrictions
-- Allows Administrators to restrict specific users from sharing documents
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS sharing_restrictions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id         BIGINT       NOT NULL,
    restricted_user_id  BIGINT       NOT NULL,
    restricted_by_id    BIGINT       NOT NULL,
    restricted_by_email VARCHAR(150) NOT NULL,
    restricted_at       TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_sharing_restriction_document_user UNIQUE (document_id, restricted_user_id),
    CONSTRAINT fk_sharing_restriction_document FOREIGN KEY (document_id)
        REFERENCES documents (id) ON DELETE CASCADE,
    CONSTRAINT fk_sharing_restriction_user FOREIGN KEY (restricted_user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_sharing_restriction_document ON sharing_restrictions (document_id);
CREATE INDEX IF NOT EXISTS idx_sharing_restriction_user ON sharing_restrictions (restricted_user_id);
