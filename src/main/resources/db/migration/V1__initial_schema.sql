-- ---------------------------------------------------------------------------
-- TrustVault PostgreSQL Schema Baseline (Flyway Migration V1)
-- ---------------------------------------------------------------------------

-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'OWNER', 'VIEWER'))
);

-- 2. Documents Table
CREATE TABLE IF NOT EXISTS documents (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name    VARCHAR(255) NOT NULL,
    file_type    VARCHAR(150) NOT NULL,
    file_size    BIGINT       NOT NULL,
    owner_id     BIGINT       NOT NULL,
    owner_email  VARCHAR(150) NOT NULL,
    category     VARCHAR(50)  NOT NULL,
    storage_key  VARCHAR(100) NOT NULL,
    content_hash VARCHAR(64)  NULL,
    uploaded_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_documents_storage_key UNIQUE (storage_key),
    CONSTRAINT fk_documents_owner FOREIGN KEY (owner_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_documents_file_size CHECK (file_size > 0 AND file_size <= 20971520)
);

CREATE INDEX IF NOT EXISTS idx_documents_owner ON documents (owner_id);
CREATE INDEX IF NOT EXISTS idx_documents_uploaded_at ON documents (uploaded_at);
CREATE INDEX IF NOT EXISTS idx_documents_category ON documents (category);

-- 3. Document Permissions Table
CREATE TABLE IF NOT EXISTS document_permissions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     BIGINT      NOT NULL,
    user_id         BIGINT      NOT NULL,
    permission      VARCHAR(20) NOT NULL,
    share_privilege VARCHAR(20) NOT NULL DEFAULT '',
    granted_at      TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_permission_document_user UNIQUE (document_id, user_id),
    CONSTRAINT fk_permission_document FOREIGN KEY (document_id)
        REFERENCES documents (id) ON DELETE CASCADE,
    CONSTRAINT fk_permission_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_permission_level CHECK (permission IN ('READ', 'EDIT'))
);

CREATE INDEX IF NOT EXISTS idx_permission_user ON document_permissions (user_id);

-- 4. Audit Chain Anchor Table (Guarantees multi-instance safe hash chaining)
CREATE TABLE IF NOT EXISTS audit_chain_anchor (
    anchor_id     INT DEFAULT 1 PRIMARY KEY,
    last_audit_id BIGINT NULL,
    head_hash     VARCHAR(64) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_single_row CHECK (anchor_id = 1)
);

-- 5. Audit Logs Table (Append-only by design)
CREATE TABLE IF NOT EXISTS audit_logs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id  BIGINT       NULL,
    actor_email    VARCHAR(150) NULL,
    document_id    BIGINT       NULL,
    document_name  VARCHAR(255) NULL,
    target_user_id BIGINT       NULL,
    target_email   VARCHAR(150) NULL,
    action         VARCHAR(50)  NOT NULL,
    outcome        VARCHAR(20)  NOT NULL,
    details        VARCHAR(1000) NULL,
    ip_address     VARCHAR(64)  NULL,
    user_agent     VARCHAR(255) NULL,
    created_at     TIMESTAMP(6) NOT NULL,
    previous_hash  VARCHAR(64)  NOT NULL,
    entry_hash     VARCHAR(64)  NOT NULL,
    CONSTRAINT ck_audit_outcome CHECK (outcome IN ('SUCCESS', 'DENIED', 'FAILURE'))
);

CREATE INDEX IF NOT EXISTS idx_audit_document ON audit_logs (document_id);
CREATE INDEX IF NOT EXISTS idx_audit_actor ON audit_logs (actor_user_id);
CREATE INDEX IF NOT EXISTS idx_audit_created_at ON audit_logs (created_at);

-- 6. Initialize Audit Anchor with GENESIS
INSERT INTO audit_chain_anchor (anchor_id, last_audit_id, head_hash, updated_at)
VALUES (1, NULL, 'GENESIS', CURRENT_TIMESTAMP);
