-- TrustVault schema - moved
--
-- This file used to contain a hand-written MySQL 8 schema. It was a second
-- description of the same tables and had already drifted from the real one
-- (it lacked document_permissions.share_privilege and audit_chain_anchor, and
-- it kept a document_share_restrictions table that no code ever used).
--
-- The authoritative schema is now Flyway and nothing else:
--
--     src/main/resources/db/migration/V1__initial_schema.sql   baseline
--     src/main/resources/db/migration/V2__reconcile_schema_drift.sql
--
-- PostgreSQL is the supported database. `spring.jpa.hibernate.ddl-auto` is
-- `validate`, so a schema that does not match the entities fails at startup
-- rather than being silently altered by Hibernate.
--
-- To build a database from scratch:
--
--     createdb -O trustvault_app trustvault_db
--     ./mvnw spring-boot:run            # Flyway applies every migration
--
-- Least privilege for the application role (run as a superuser once, after
-- the migrations have been applied by a role that may create objects):
--
--     GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO trustvault_app;
--     GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO trustvault_app;
--     ALTER DEFAULT PRIVILEGES IN SCHEMA public
--         GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO trustvault_app;
--
-- Note: the application never updates or deletes audit_logs rows. Revoking
-- UPDATE and DELETE on that table specifically is supported and recommended:
--
--     REVOKE UPDATE, DELETE ON audit_logs FROM trustvault_app;
-- ---------------------------------------------------------------------------
